def _load_session(source: Path) -> dict[str, Any]:
    """Load a native session through the existing NeuroStation parser."""
    import numpy as np

    from eeg_tools.workstation import v9_offline as baseline
    from scripts.diagnose_neurostation_v9_output import parse_raw, validate_metadata

    source = source.resolve()
    _require(source.is_dir(), f"session directory does not exist: {source}")
    paths = _session_source_paths(source)
    _require(all(path.is_file() for path in paths.values()), f"native session files are incomplete: {source}")
    before = baseline._source_hashes(source)
    session = _read_json(paths["session.json"])
    channels = _read_json(paths["channel_config.json"])
    validate_metadata(session, channels)
    raw, header = parse_raw(paths["raw_brainflow.tsv"].read_bytes())
    _require(raw.ndim == 2 and raw.shape[1] == 8 and raw.dtype.kind == "f", "raw parser returned invalid shape")
    _require(bool(np.isfinite(raw).all()), "raw session contains nonfinite samples")
    targets, trials, reason = baseline._classification_inputs(source, raw)
    _require(not reason, reason or "classification metadata unavailable")
    _require(targets, "session has no declared SSVEP targets")
    parsed_trials: list[dict[str, Any]] = []
    for trial in trials:
        start = trial.get("window_start_sample_index")
        end = trial.get("offset_sample_index")
        onset = trial.get("onset_sample_index")
        _require(not trial.get("unavailable_reason"), f"trial {trial.get('trial_index')} unavailable: {trial.get('unavailable_reason')}")
        _require(all(isinstance(v, int) for v in (start, end, onset)), f"trial {trial.get('trial_index')} indices are invalid")
        _require(0 <= start < end <= raw.shape[0], f"trial {trial.get('trial_index')} stimulus window is invalid")
        rest_start = max(0, onset - 750)
        rest_end = onset
        _require(rest_end - rest_start >= 250, f"trial {trial.get('trial_index')} rest window is too short")
        _require(end - start >= 250, f"trial {trial.get('trial_index')} stimulus window is too short")
        parsed_trials.append({
            "trial_index": int(trial["trial_index"]),
            "recorded_presentation_target_id": str(trial.get("presented_target_id") or ""),
            "onset_sample_index": onset,
            "window_start_sample_index": start,
            "offset_sample_index": end,
            "rest_start_sample_index": rest_start,
            "rest_end_sample_index": rest_end,
            "signal": np.asarray(raw[start:end].T, dtype=np.float64),
            "rest_signal": np.asarray(raw[rest_start:rest_end].T, dtype=np.float64),
        })
    after = baseline._source_hashes(source)
    _require(before == after, "session source changed while loading")
    return {
        "source_session": str(source),
        "session_name": source.name,
        "source_hashes": before,
        "header": list(header),
        "sample_count": int(raw.shape[0]),
        "targets": [(str(identifier), float(frequency)) for identifier, frequency in targets],
        "trials": parsed_trials,
    }


def _validate_targets(targets: Iterable[tuple[str, float]]) -> list[tuple[str, float]]:
    result = [(str(identifier), float(frequency)) for identifier, frequency in targets]
    _require(result, "targets must be nonempty")
    _require(len({identifier for identifier, _ in result}) == len(result), "target identifiers must be unique")
    _require(len({frequency for _, frequency in result}) == len(result), "target frequencies must be unique")
    _require(all(0 < frequency < SAMPLE_RATE_HZ / 2 for _, frequency in result), "target frequency outside Nyquist")
    return result


def _preprocess(signal: Any, bandpass_hz: tuple[float, float]) -> Any:
    import numpy as np
    from scipy.signal import butter, filtfilt, iirnotch, sosfiltfilt

    x = np.asarray(signal, dtype=np.float64)
    _require(x.ndim == 2 and x.shape[0] == 8 and x.shape[1] >= 250, "signal must be [8, samples]")
    _require(bool(np.isfinite(x).all()), "signal contains nonfinite values")
    low, high = map(float, bandpass_hz)
    _require(0 < low < high < SAMPLE_RATE_HZ / 2, "invalid bandpass")
    b, a = iirnotch(NOTCH_FREQUENCY_HZ, NOTCH_Q, fs=SAMPLE_RATE_HZ)
    filtered = filtfilt(b, a, x, axis=1)
    sos = butter(FILTER_ORDER, [low, high], btype="bandpass", fs=SAMPLE_RATE_HZ, output="sos")
    filtered = sosfiltfilt(sos, filtered, axis=1)
    filtered = filtered - np.mean(filtered, axis=1, keepdims=True)
    _require(bool(np.isfinite(filtered).all()), "preprocessing produced nonfinite values")
    return filtered


def _reference(frequency_hz: float, harmonics: int, samples: int) -> Any:
    import numpy as np

    t = np.arange(samples, dtype=np.float64) / SAMPLE_RATE_HZ
    rows = []
    for harmonic in range(1, harmonics + 1):
        rows.append(np.sin(2 * np.pi * frequency_hz * harmonic * t))
        rows.append(np.cos(2 * np.pi * frequency_hz * harmonic * t))
    y = np.asarray(rows, dtype=np.float64)
    return y - np.mean(y, axis=1, keepdims=True)


def _inverse_sqrt(matrix: Any) -> Any:
    import numpy as np

    scale = float(np.trace(matrix) / matrix.shape[0])
    _require(_finite(scale) and scale > 0, "CCA covariance is degenerate")
    values, vectors = np.linalg.eigh(matrix + COVARIANCE_REGULARIZATION * scale * np.eye(matrix.shape[0]))
    _require(bool(np.all(values > 0)), "CCA covariance eigensystem is invalid")
    return (vectors * (1.0 / np.sqrt(values))) @ vectors.T


def cca_score(signal: Any, frequency_hz: float, harmonics: int, channel_indices: Iterable[int]) -> float:
    """Compute a regularized multi-harmonic canonical correlation score."""
    import numpy as np

    indices = tuple(int(index) for index in channel_indices)
    _require(indices in PREREGISTERED_CHANNEL_SUBSETS.values(), "channel subset is not preregistered")
    _require(harmonics in HARMONIC_COUNTS, "harmonic count is not preregistered")
    x = np.asarray(signal, dtype=np.float64)[list(indices), :]
    y = _reference(float(frequency_hz), harmonics, x.shape[1])
    x = x - np.mean(x, axis=1, keepdims=True)
    n = x.shape[1] - 1
    _require(n > 0, "CCA input is too short")
    cxx = x @ x.T / n
    cyy = y @ y.T / n
    cxy = x @ y.T / n
    value = float(np.linalg.svd(_inverse_sqrt(cxx) @ cxy @ _inverse_sqrt(cyy), compute_uv=False)[0])
    _require(_finite(value), "CCA score is nonfinite")
    return float(min(1.0, max(0.0, value)))


def _condition_id(subset_name: str, harmonics: int, mode: str, band_name: str | None = None) -> str:
    if mode == "single":
        return f"{subset_name}__h{harmonics}__{band_name}"
    return f"{subset_name}__h{harmonics}__filterbank_weighted"


def _all_bandpasses() -> dict[str, tuple[float, float]]:
    result = dict(SINGLE_BANDPASSES)
    for low, high in FILTERBANK_BANDS:
        result[f"fb_{low:g}_{high:g}"] = (low, high)
    return result


def _prepare_fold_trials(fold: Mapping[str, Any]) -> dict[tuple[str, int], dict[str, Any]]:
    prepared: dict[tuple[str, int], dict[str, Any]] = {}
    bands = _all_bandpasses()
    for role in ("calibration", "evaluation"):
        for trial in fold[role]["trials"]:
            by_band: dict[str, dict[str, Any]] = {}
            for band_name, band in bands.items():
                by_band[band_name] = {
                    "stimulus": _preprocess(trial["signal"], band),
                    "rest": _preprocess(trial["rest_signal"], band),
                }
            prepared[(role, trial["trial_index"])] = by_band
    return prepared


def _score_trial(prepared_trial: Mapping[str, Any], targets: list[tuple[str, float]], *, harmonics: int, channel_indices: tuple[int, ...], mode: str, band_name: str | None, filterbank_weights: list[float] | None = None) -> dict[str, Any]:
    import numpy as np

    if mode == "single":
        _require(band_name in SINGLE_BANDPASSES, "single condition band is invalid")
        bands = [(band_name, 1.0)]
    else:
        _require(filterbank_weights is not None and len(filterbank_weights) == len(FILTERBANK_BANDS), "filterbank weights are missing")
        bands = [(f"fb_{low:g}_{high:g}", float(weight)) for (low, high), weight in zip(FILTERBANK_BANDS, filterbank_weights)]
    stimulus_by_band: dict[str, dict[str, float]] = {}
    rest_by_band: dict[str, dict[str, float]] = {}
    for current_band, _ in bands:
        signals = prepared_trial[current_band]
        stimulus_by_band[current_band] = {
            identifier: cca_score(signals["stimulus"], frequency, harmonics, channel_indices)
            for identifier, frequency in targets
        }
        rest_by_band[current_band] = {
            identifier: cca_score(signals["rest"], frequency, harmonics, channel_indices)
            for identifier, frequency in targets
        }
    scores = {
        identifier: float(sum(weight * stimulus_by_band[band][identifier] for band, weight in bands))
        for identifier, _ in targets
    }
    rest_scores = {
        identifier: float(sum(weight * rest_by_band[band][identifier] for band, weight in bands))
        for identifier, _ in targets
    }
    _require(bool(np.isfinite(list(scores.values())).all()), "trial score is nonfinite")
    return {
        "scores": scores,
        "rest_scores": rest_scores,
        "stimulus_scores_by_band": stimulus_by_band,
        "rest_scores_by_band": rest_by_band,
    }


def _fit_filterbank_weights(calibration_score_rows: list[dict[str, Any]], targets: list[tuple[str, float]]) -> list[float]:
    import numpy as np

    target_ids = [identifier for identifier, _ in targets]
    discriminations = []
    for band_name in [f"fb_{low:g}_{high:g}" for low, high in FILTERBANK_BANDS]:
        values = []
        for row in calibration_score_rows:
            scores = row["stimulus_scores_by_band"][band_name]
            correct = float(scores[row["recorded_presentation_target_id"]])
            incorrect = [float(scores[target]) for target in target_ids if target != row["recorded_presentation_target_id"]]
            values.append(correct - (sum(incorrect) / len(incorrect)))
        discrimination = float(np.mean(values)) if values else 0.0
        discriminations.append(max(discrimination, 0.0) + 1e-9)
    total = float(sum(discriminations))
    return [float(value / total) for value in discriminations]


def _fit_condition(calibration_rows: list[dict[str, Any]], prepared: Mapping[tuple[str, int], Mapping[str, Any]], targets: list[tuple[str, float]], *, subset_name: str, harmonics: int, mode: str, band_name: str | None) -> tuple[dict[str, Any], list[dict[str, Any]]]:
    import numpy as np

    indices = PREREGISTERED_CHANNEL_SUBSETS[subset_name]
    preliminary_weights = [1.0 / len(FILTERBANK_BANDS)] * len(FILTERBANK_BANDS) if mode == "filterbank" else None
    calibration_scores: list[dict[str, Any]] = []
    for trial in calibration_rows:
        scored = _score_trial(prepared[("calibration", trial["trial_index"])], targets, harmonics=harmonics, channel_indices=indices, mode=mode, band_name=band_name, filterbank_weights=preliminary_weights)
        calibration_scores.append({**scored, "recorded_presentation_target_id": trial["recorded_presentation_target_id"], "trial_index": trial["trial_index"]})
    weights = _fit_filterbank_weights(calibration_scores, targets) if mode == "filterbank" else None
    if mode == "filterbank":
        calibration_scores = []
        for trial in calibration_rows:
            scored = _score_trial(prepared[("calibration", trial["trial_index"])], targets, harmonics=harmonics, channel_indices=indices, mode=mode, band_name=None, filterbank_weights=weights)
            calibration_scores.append({**scored, "recorded_presentation_target_id": trial["recorded_presentation_target_id"], "trial_index": trial["trial_index"]})
    target_ids = [identifier for identifier, _ in targets]
    correct_scores = [row["scores"][row["recorded_presentation_target_id"]] for row in calibration_scores]
    margins = []
    for row in calibration_scores:
        ordered = sorted((float(score), identifier) for identifier, score in row["scores"].items())
        margins.append(float(ordered[-1][0] - ordered[-2][0]))
    score_threshold = max(0.0, float(np.quantile(correct_scores, 0.10)))
    margin_threshold = max(0.0, float(np.quantile(margins, 0.10)))
    model = {
        "condition_id": _condition_id(subset_name, harmonics, mode, band_name),
        "channel_subset_name": subset_name,
        "channel_indices": list(indices),
        "channel_names": [f"CH{index + 1}" for index in indices],
        "harmonics": int(harmonics),
        "mode": mode,
        "bandpass_hz": None if mode == "filterbank" else list(SINGLE_BANDPASSES[band_name]),
        "filterbank_bands_hz": [list(value) for value in FILTERBANK_BANDS] if mode == "filterbank" else None,
        "filterbank_weights": weights,
        "acceptance_thresholds": {
            "score": score_threshold,
            "margin": margin_threshold,
            "fit_quantiles": {"score": 0.10, "margin": 0.10},
            "fit_scope": "calibration_session_only",
        },
        "calibration_trial_count": len(calibration_rows),
        "calibration_target_counts": {target: sum(row["recorded_presentation_target_id"] == target for row in calibration_rows) for target in target_ids},
        "recorded_labels_used_for_fit_only": True,
        "evaluation_labels_used_for_fit": False,
    }
    return model, calibration_scores


def _predict(prepared_trial: Mapping[str, Any], model: Mapping[str, Any], targets: list[tuple[str, float]]) -> dict[str, Any]:
    mode = str(model["mode"])
    scores = _score_trial(
        prepared_trial,
        targets,
        harmonics=int(model["harmonics"]),
        channel_indices=tuple(model["channel_indices"]),
        mode=mode,
        band_name=None if mode == "filterbank" else str(model["condition_id"]).rsplit("__", 1)[-1],
        filterbank_weights=model["filterbank_weights"],
    )
    ordered = sorted(((float(score), identifier) for identifier, score in scores["scores"].items()), key=lambda item: (-item[0], target_ids_order(targets).index(item[1])))
    best_score, best_id = ordered[0]
    second_score = ordered[1][0] if len(ordered) > 1 else best_score
    margin = float(best_score - second_score)
    thresholds = model["acceptance_thresholds"]
    accepted = bool(best_score >= float(thresholds["score"]) and margin >= float(thresholds["margin"]))
    return {
        "available": True,
        "decision": "accepted" if accepted else "unknown",
        "accepted": accepted,
        "target_id": best_id if accepted else None,
        "best_candidate_target_id": best_id,
        "rejection_reason": None if accepted else "calibration_threshold_not_met",
        "best_score": best_score,
        "second_score": second_score,
        "margin": margin,
        "scores": scores["scores"],
        "rest_scores": scores["rest_scores"],
        "stimulus_scores_by_band": scores["stimulus_scores_by_band"],
        "rest_scores_by_band": scores["rest_scores_by_band"],
        "recorded_label_used_in_forward": False,
        "presented_matches_are_gaze_accuracy": False,
    }


def target_ids_order(targets: list[tuple[str, float]]) -> list[str]:
    return [identifier for identifier, _ in targets]


def _stats(rows: list[dict[str, Any]], targets: list[tuple[str, float]]) -> dict[str, Any]:
    target_ids = target_ids_order(targets)
    accepted = [row for row in rows if row["prediction"]["accepted"]]
    per_target: dict[str, Any] = {}
    for target_id in target_ids:
        subset = [row for row in rows if row["recorded_presentation_target_id"] == target_id]
        matched = [row for row in subset if row["presented_match"]]
        accepted_subset = [row for row in subset if row["prediction"]["accepted"]]
        per_target[target_id] = {
            "trial_count": len(subset),
            "accepted_count": len(accepted_subset),
            "unknown_count": len(subset) - len(accepted_subset),
            "proxy_match_count": len(matched),
            "accepted_proxy_match_count": sum(row["presented_match"] for row in accepted_subset),
            "accepted_proxy_match_rate": (float(sum(row["presented_match"] for row in accepted_subset) / len(accepted_subset)) if accepted_subset else None),
            "trial_indices": [row["trial_index"] for row in subset],
        }
    twenty = next((identifier for identifier, frequency in targets if math.isclose(frequency, 20.0)), None)
    twenty_rows = [row for row in rows if twenty is not None and row["recorded_presentation_target_id"] == twenty]
    return {
        "evaluation_trial_count": len(rows),
        "accepted_count": len(accepted),
        "unknown_count": len(rows) - len(accepted),
        "proxy_match_count": sum(row["presented_match"] for row in rows),
        "accepted_proxy_match_count": sum(row["presented_match"] for row in accepted),
        "accepted_proxy_match_rate": (float(sum(row["presented_match"] for row in accepted) / len(accepted)) if accepted else None),
        "per_target": per_target,
        "twenty_hz": {
            "target_id": twenty,
            "trial_count": len(twenty_rows),
            "accepted_count": sum(row["prediction"]["accepted"] for row in twenty_rows),
            "unknown_count": sum(not row["prediction"]["accepted"] for row in twenty_rows),
            "proxy_match_count": sum(row["presented_match"] for row in twenty_rows),
            "trials": [
                {
                    "trial_index": row["trial_index"],
                    "decision": row["prediction"]["decision"],
                    "accepted": row["prediction"]["accepted"],
                    "target_id": row["prediction"]["target_id"],
                    "best_candidate_target_id": row["prediction"]["best_candidate_target_id"],
                    "presented_match": row["presented_match"],
                    "best_score": row["prediction"]["best_score"],
                    "margin": row["prediction"]["margin"],
                }
                for row in twenty_rows
            ],
        },
        "matching_definition": "accepted prediction equals recorded presentation label; this is a proxy match, not gaze accuracy",
    }


def _evaluate_condition(calibration_fold: Mapping[str, Any], prepared: Mapping[tuple[str, int], Mapping[str, Any]], targets: list[tuple[str, float]], *, subset_name: str, harmonics: int, mode: str, band_name: str | None) -> dict[str, Any]:
    model, calibration_scores = _fit_condition(calibration_fold["calibration"]["trials"], prepared, targets, subset_name=subset_name, harmonics=harmonics, mode=mode, band_name=band_name)
    rows = []
    for trial in calibration_fold["evaluation"]["trials"]:
        prediction = _predict(prepared[("evaluation", trial["trial_index"])], model, targets)
        recorded = trial["recorded_presentation_target_id"]
        presented_match = bool(prediction["accepted"] and prediction["target_id"] == recorded)
        rows.append({
            "trial_index": trial["trial_index"],
            "recorded_presentation_target_id": recorded,
            "target_frequency_hz": next((frequency for identifier, frequency in targets if identifier == recorded), None),
            "prediction": prediction,
            "presented_match": presented_match,
        })
    return {
        "condition": model,
        "calibration_fit_summary": {
            "calibration_trial_count": len(calibration_fold["calibration"]["trials"]),
            "calibration_target_counts": model["calibration_target_counts"],
            "filterbank_weights": model["filterbank_weights"],
            "recorded_labels_used_for_fit_only": True,
            "evaluation_forward_uses_recorded_labels": False,
            "calibration_score_examples": [
                {"trial_index": row["trial_index"], "recorded_presentation_target_id": row["recorded_presentation_target_id"], "scores": row["scores"]}
                for row in calibration_scores
            ],
        },
        "evaluation_trials": rows,
        "summary": _stats(rows, targets),
    }


def run_experiment(session_paths: Iterable[str | Path] = DEFAULT_SESSION_PATHS) -> dict[str, Any]:
    """Run both directions of a strict two-session cross-session holdout."""
    validate_experiment_config()
    paths = tuple(Path(path).resolve() for path in session_paths)
    _require(len(paths) == 2, "exactly two sessions are required for strict cross-session holdout")
    _require(len({str(path).casefold() for path in paths}) == 2, "the two sessions must be distinct")
    sessions = [_load_session(path) for path in paths]
    targets = _validate_targets(sessions[0]["targets"])
    _require(sessions[1]["targets"] == targets, "session target definitions differ")

    folds = []
    for calibration_index, evaluation_index in ((0, 1), (1, 0)):
        calibration = sessions[calibration_index]
        evaluation = sessions[evaluation_index]
        fold = {"calibration": calibration, "evaluation": evaluation}
        prepared = _prepare_fold_trials(fold)
        conditions = []
        for subset_name in PREREGISTERED_CHANNEL_SUBSETS:
            for harmonics in HARMONIC_COUNTS:
                for band_name in SINGLE_BANDPASSES:
                    conditions.append(_evaluate_condition(fold, prepared, targets, subset_name=subset_name, harmonics=harmonics, mode="single", band_name=band_name))
                conditions.append(_evaluate_condition(fold, prepared, targets, subset_name=subset_name, harmonics=harmonics, mode="filterbank", band_name=None))
        folds.append({
            "fold_id": f"calibration_{calibration['session_name']}__evaluation_{evaluation['session_name']}",
            "calibration_session": calibration["source_session"],
            "evaluation_session": evaluation["source_session"],
            "calibration_trial_count": len(calibration["trials"]),
            "evaluation_trial_count": len(evaluation["trials"]),
            "conditions": conditions,
        })

    from eeg_tools.workstation import v9_offline as baseline
    final_hashes = {session["source_session"]: baseline._source_hashes(Path(session["source_session"])) for session in sessions}
    initial_hashes = {session["source_session"]: session["source_hashes"] for session in sessions}
    _require(initial_hashes == final_hashes, "source session files changed during experiment")
    report = {
        "schema_version": 1,
        "status": "formal",
        "completion_status": "complete",
        "created_at_utc": datetime.now(timezone.utc).isoformat(),
        "experiment": validate_experiment_config(),
        "experiment_config_sha256": _canonical_sha256(validate_experiment_config()),
        "targets": [[identifier, frequency] for identifier, frequency in targets],
        "channel_subsets": {name: {"indices": list(indices), "names": [f"CH{index + 1}" for index in indices], "selection": "preregistered"} for name, indices in PREREGISTERED_CHANNEL_SUBSETS.items()},
        "sessions": [
            {
                "source_session": session["source_session"],
                "session_name": session["session_name"],
                "source_hashes_before": session["source_hashes"],
                "source_hashes_after": final_hashes[session["source_session"]],
                "trial_count": len(session["trials"]),
                "sample_count": session["sample_count"],
            }
            for session in sessions
        ],
        "folds": folds,
        "source_sessions_modified": False,
        "all_parameters_fit_only_on_calibration": True,
        "evaluation_forward_received_recorded_labels": False,
        "limitations": [
            "Exploratory offline experiment only; no runtime or default desktop change.",
            "Both directions are cross-session holdouts, but there are only two sessions from one participant.",
            "Recorded presentation labels are proxy metadata and are not independent gaze truth.",
            "Presented matches must not be interpreted as gaze accuracy, clinical validity, or deployment readiness.",
            "Channel subsets and filterbank bands are preregistered in this script; no evaluation-driven channel selection is performed.",
            "Calibration-side thresholds and filterbank weights are refit separately for each fold using calibration labels only.",
        ],
        **FALSE_FLAGS,
    }
    return report


def _atomic_write(path: Path, report: dict[str, Any]) -> None:
    path = path.resolve()
    pending = path.with_name(path.name + ".pending")
    _require(not path.exists(), f"report already exists: {path}")
    path.parent.mkdir(parents=True, exist_ok=True)
    with pending.open("x", encoding="utf-8", newline="\n") as handle:
        json.dump(report, handle, ensure_ascii=False, indent=2, allow_nan=False)
        handle.write("\n")
        handle.flush()
        os.fsync(handle.fileno())
    os.replace(pending, path)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--session", action="append", type=Path, help="exactly two native sessions; omitted uses the two fixed 2026-10-04 sessions")
    parser.add_argument("--output", required=True, type=Path, help="new JSON report; recommended under analysis_outputs/history")
    args = parser.parse_args(argv)
    try:
        sessions = DEFAULT_SESSION_PATHS if args.session is None else tuple(args.session)
        report = run_experiment(sessions)
        _atomic_write(args.output, report)
    except (OSError, ValueError, KeyError, TypeError, ArithmeticError) as exc:
        error = {"status": "formal", "completion_status": "incomplete", "error": str(exc), **FALSE_FLAGS}
        print(json.dumps(error, ensure_ascii=False), file=sys.stderr)
        return 1
    compact = {
        "status": report["status"],
        "completion_status": report["completion_status"],
        "report": str(args.output.resolve()),
        "fold_count": len(report["folds"]),
        **FALSE_FLAGS,
    }
    print(json.dumps(compact, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
